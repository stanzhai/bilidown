//! `test/…/test_subtitle_ass.py` vectors: template, style line, dialogues.

mod common;

use common::*;
use extras::ass::{generate, SubtitleStyle};

#[test]
fn default_style_line() {
    let s = SubtitleStyle::default_style();
    let doc = generate(&subtitle_body(), "标题", &s);
    let style_line = doc
        .lines()
        .find(|l| l.starts_with("Style: Default"))
        .unwrap();
    assert_eq!(
        style_line,
        "Style: Default,黑体,36,&H00FFFFFF,&H000000FF,H00000000,H00000000,0,0,0,0,100,100,0,0,1,1.0,0.0,2,10,10,20,1"
    );
}

#[test]
fn document_shape() {
    let doc = generate(&subtitle_body(), "标题", &SubtitleStyle::default_style());
    let expected_head = "\
[Script Info]
; Script generated by Bili23 Downloader
; http://bili23.scott-sloan.cn
Title: 标题
ScriptType: v4.00+
WrapStyle: 2
Collisions: Normal
ScaledBorderAndShadow: yes
Aspect Ratio: 1280:720
YCbCr Matrix: TV.601
PlayResX: 1280
PlayResY: 720

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
";
    assert!(doc.starts_with(expected_head), "head mismatch:\n{}", &doc[..expected_head.len().min(doc.len())]);
    let events = &doc[doc.find("[Events]").unwrap()..];
    assert_eq!(
        events,
        "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\nDialogue: 0,0:00:01.50,0:00:03.25,Default,,0,0,0,,你好 world\nDialogue: 0,0:00:10.00,0:00:12.50,Default,,0,0,0,,第二行\n"
    );
}

#[test]
fn custom_style_from_config() {
    let cfg = serde_json::json!({
        "font": {"name": "思源黑体", "size": 48, "bold": true, "italic": false, "underline": false, "strike": false},
        "border": {"border": 2.5, "shadow": 1.0},
        "color": {"primary": "&H000000FF", "secondary": "&H00FFFFFF", "border": "&H00000000", "shadow": "&H00000000"},
        "margin": {"left": 20, "right": 30, "vertical": 40},
        "resolution": {"width": 1920, "height": 1080},
        "Alignment": 8
    });
    let s = SubtitleStyle::from_config(&cfg);
    let doc = generate(&subtitle_body(), "T", &s);
    let style_line = doc.lines().find(|l| l.starts_with("Style: Default")).unwrap();
    assert_eq!(
        style_line,
        "Style: Default,思源黑体,48,&H000000FF,&H00FFFFFF,&H00000000,&H00000000,1,0,0,0,100,100,0,0,1,2.5,1.0,8,20,30,40,1"
    );
    assert!(doc.contains("Aspect Ratio: 1920:1080"));
    assert!(doc.contains("PlayResX: 1920"));
}

#[test]
fn missing_config_falls_back_to_defaults() {
    let s = SubtitleStyle::from_config(&serde_json::json!({}));
    assert_eq!(s, SubtitleStyle::default_style());
}
